static uint8_t xt(uint8_t x) { return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0)); }
static uint8_t gmul(uint8_t a, uint8_t b)
{
    uint8_t r = 0;
    while (b) {
        if (b & 1) r ^= a;
        a = xt(a);
        b >>= 1;
    }
    return r;
}

static uint32_t sub_word(uint32_t w)
{
    return (uint32_t)SBOX[w >> 24] << 24 | (uint32_t)SBOX[(w >> 16) & 0xff] << 16 |
           (uint32_t)SBOX[(w >> 8) & 0xff] << 8 | SBOX[w & 0xff];
}

void tg_aes256_setkey(tg_aes256_t *c, const uint8_t key[32])
{
    uint8_t rcon = 1;
    for (int i = 0; i < 8; i++)
        c->rk[i] = (uint32_t)key[4 * i] << 24 | (uint32_t)key[4 * i + 1] << 16 | (uint32_t)key[4 * i + 2] << 8 | key[4 * i + 3];
    for (int i = 8; i < 60; i++) {
        uint32_t t = c->rk[i - 1];
        if (i % 8 == 0) {
            t = sub_word(t << 8 | t >> 24) ^ ((uint32_t)rcon << 24);
            rcon = xt(rcon);
        } else if (i % 8 == 4) {
            t = sub_word(t);
        }
        c->rk[i] = c->rk[i - 8] ^ t;
    }
}

static void add_rk(uint8_t *s, const uint32_t *rk)
{
    for (int i = 0; i < 4; i++) {
        s[4 * i] ^= (uint8_t)(rk[i] >> 24); s[4 * i + 1] ^= (uint8_t)(rk[i] >> 16);
        s[4 * i + 2] ^= (uint8_t)(rk[i] >> 8); s[4 * i + 3] ^= (uint8_t)rk[i];
    }
}

/* state is column-major as in FIPS 197: s[4*col + row] */
void tg_aes256_encrypt(const tg_aes256_t *c, const uint8_t in[16], uint8_t out[16])
{
    uint8_t s[16], t[16];
    tg_memcpy(s, in, 16);
    add_rk(s, c->rk);
    for (int r = 1; r <= 14; r++) {
        for (int i = 0; i < 16; i++)                       /* SubBytes + ShiftRows */
            t[i] = SBOX[s[(i + 4 * (i & 3)) & 15]];
        if (r < 14) {
            for (int col = 0; col < 4; col++) {            /* MixColumns */
                uint8_t *p = t + 4 * col, a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
                uint8_t all = a0 ^ a1 ^ a2 ^ a3;
                p[0] ^= all ^ xt(a0 ^ a1);
                p[1] ^= all ^ xt(a1 ^ a2);
                p[2] ^= all ^ xt(a2 ^ a3);
                p[3] ^= all ^ xt(a3 ^ a0);
            }
        }
        tg_memcpy(s, t, 16);
        add_rk(s, c->rk + 4 * r);
    }
    tg_memcpy(out, s, 16);
}

void tg_aes256_decrypt(const tg_aes256_t *c, const uint8_t in[16], uint8_t out[16])
{
    uint8_t s[16], t[16];
    tg_memcpy(s, in, 16);
    add_rk(s, c->rk + 56);
    for (int r = 13; r >= 0; r--) {
        for (int i = 0; i < 16; i++)                       /* InvShiftRows + InvSubBytes */
            t[(i + 4 * (i & 3)) & 15] = INV_SBOX[s[i]];
        add_rk(t, c->rk + 4 * r);
        if (r > 0) {
            for (int col = 0; col < 4; col++) {            /* InvMixColumns */
                uint8_t *p = t + 4 * col, a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
                p[0] = gmul(a0, 14) ^ gmul(a1, 11) ^ gmul(a2, 13) ^ gmul(a3, 9);
                p[1] = gmul(a0, 9) ^ gmul(a1, 14) ^ gmul(a2, 11) ^ gmul(a3, 13);
                p[2] = gmul(a0, 13) ^ gmul(a1, 9) ^ gmul(a2, 14) ^ gmul(a3, 11);
                p[3] = gmul(a0, 11) ^ gmul(a1, 13) ^ gmul(a2, 9) ^ gmul(a3, 14);
            }
        }
        tg_memcpy(s, t, 16);
    }
    tg_memcpy(out, s, 16);
}

/* IGE: c_i = E(p_i ^ c_{i-1}) ^ p_{i-1};  p_i = D(c_i ^ p_{i-1}) ^ c_{i-1} */
static void ige(const uint8_t key[32], const uint8_t iv[32], const uint8_t *in, uint8_t *out, uint32_t len, int enc)
{
    tg_aes256_t k;
    uint8_t prev_x[16], prev_y[16], cur[16], tmp[16];
    tg_aes256_setkey(&k, key);
    /* enc: x = plaintext, y = ciphertext; dec: x = ciphertext, y = plaintext */
    tg_memcpy(prev_y, enc ? iv : iv + 16, 16);
    tg_memcpy(prev_x, enc ? iv + 16 : iv, 16);
    for (uint32_t off = 0; off + 16 <= len; off += 16) {
        tg_memcpy(cur, in + off, 16);
        for (int i = 0; i < 16; i++) tmp[i] = cur[i] ^ prev_y[i];
        if (enc) tg_aes256_encrypt(&k, tmp, tmp); else tg_aes256_decrypt(&k, tmp, tmp);
        for (int i = 0; i < 16; i++) tmp[i] ^= prev_x[i];
        tg_memcpy(out + off, tmp, 16);
        tg_memcpy(prev_x, cur, 16);
        tg_memcpy(prev_y, tmp, 16);
    }
    tg_wipe(&k, sizeof k);
}

void tg_aes_ige_encrypt(const uint8_t key[32], const uint8_t iv[32], const uint8_t *in, uint8_t *out, uint32_t len)
{ ige(key, iv, in, out, len, 1); }

void tg_aes_ige_decrypt(const uint8_t key[32], const uint8_t iv[32], const uint8_t *in, uint8_t *out, uint32_t len)
{ ige(key, iv, in, out, len, 0); }
